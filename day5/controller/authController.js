const User = require("../models/users");
const bcryptjs = require("bcryptjs");
const { makeToken } = require("../utilis/makeToken")

exports.register = async (req,res,next) => {
    try{
        const {name, email ,password, confirmPassword} = req.body;
        if(!name){
            return res.status(404).json({
                message : "Name is not found"
            })
        }
        if(!email){
            return res.status(404).json({
                message : "Email is not found"
            })
        }
        if(!password || password<6){
            return res.status(404).json({
                message : "Enter Correct Password"
            })
        }


        if(password != confirmPassword){
            return res.status(404).json({
                message : "password and confirmPassword is not same"
            })
        }

        // Hash the password securely using bcrypt with 10 salt rounds (higher cost = more secure but slower)

        const hashedPassword = await bcryptjs.hash(password,10);

        // Create a new user in the database with name, email, and hashed password
        const user = await User.create({
            name,
            email,
            password: hashedPassword
        })

        return res.status(201).json({
            id: user._id,  // Return the unique ID generated by MongoDB
            name: user.name, // Return the user's name
            email:user.email  // Return the user's email
        })
    }
    catch(err){
        next(err);
    }
}

exports.login = async (req,res,next) => {
    try{
        const {email, password} = req.body;

        if(!email){
            return res.status(401).json({
                message: "Email not found"
            })
        }

        if(!password || password.length < 6){
            return res.status(401).json({
                message: "Password not found"
            })
        }
        const user = await User.findOne({email}).select("+password");

        if(!user){
            return res.status(401).json({
                message: "User doesn't Exist"
            })
        }

        const ok = await bcryptjs.compare(password, user.password);
        if(!ok){
            return res.status(400).json({
                message: "Invalid email or Password"
            })
        }

        res.status(200).json({
            token : makeToken(user)
        })
    }
    catch(err){
        next(err);
    }
}